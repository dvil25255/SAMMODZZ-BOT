create table if not exists public.bot_files (
  id text primary key,
  original_name text not null,
  stored_name text not null,
  storage_type text not null check (storage_type in ('scripts', 'offsets')),
  size_bytes bigint not null,
  sha256 text not null,
  uploaded_by bigint not null,
  created_at timestamptz not null default now()
);

create table if not exists public.bot_activity (
  id bigint generated by default as identity primary key,
  actor_id bigint not null,
  action text not null,
  details text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.bot_licenses (
  id bigint generated by default as identity primary key,
  key_hash text not null unique,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create index if not exists bot_files_created_at_idx on public.bot_files (created_at desc);
create index if not exists bot_activity_created_at_idx on public.bot_activity (created_at desc);

alter table public.bot_files enable row level security;
alter table public.bot_activity enable row level security;
alter table public.bot_licenses enable row level security;

